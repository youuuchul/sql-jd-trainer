import { chromium } from "@playwright/test";
import { readFileSync } from "node:fs";
const p = JSON.parse(readFileSync("content/problems/basics/ba-01-where-in-compare.json", "utf-8"));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto("http://localhost:3100/");
await page.screenshot({ path: "e2e/shots/home.png" });
await page.goto(`http://localhost:3100/problems/${p.id}`);
await page.getByText("준비됨").waitFor({ timeout: 90000 });
await page.locator(".cm-content").click();
await page.keyboard.insertText(p.wrongPatterns[0].sql.postgres);
await page.getByRole("button", { name: /실행/ }).click();
await page.getByText("오답", { exact: true }).waitFor();
await page.screenshot({ path: "e2e/shots/workspace-wrong.png" });
await page.locator(".cm-content").click();
await page.keyboard.press("Meta+A"); await page.keyboard.press("Backspace");
await page.keyboard.insertText(p.solutions.postgres);
await page.getByRole("button", { name: /실행/ }).click();
await page.getByText("정답", { exact: true }).waitFor();
await page.screenshot({ path: "e2e/shots/workspace-pass.png", fullPage: true });
await page.goto("http://localhost:3100/mock/archive-mock");
await page.screenshot({ path: "e2e/shots/mock-intro.png" });
await browser.close();
console.log("shots done");
